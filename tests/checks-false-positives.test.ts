import { expect, it } from 'vitest';
import { runChecks } from '../src/core/analysis/debug';
import { parseSjson } from '../src/core/sjson';

const opts = { shortBeam: 0.001, closeNodes: 0.002, minBeams: 3, mirrorTolerance: 0.01, suffixL: 'l', suffixR: 'r' };
const part = { def: { name: 'p', file: 'f.jbeam' } };
const row = (v: Record<string, any> = {}, s = 0) => ({ part, v, src: { section: 'x', file: 'f.jbeam', node: { s, e: s + 5 } } });
const node = (name: string, x: number, v: Record<string, any> = {}, groups: string[] = []) => ({ name, x, y: 0, z: 0, row: row(v), groups });
const beam = (a: number, b: number, v: Record<string, any> = {}, s = 0) => ({ a, b, section: 'beams', row: row(v, s) });

function vehicle(extra: Record<string, any>) {
  const nodes = extra.nodes ?? [node('a', 0), node('b', 1)];
  return { nodes, nodeIndex: new Map(nodes.map((n: any, i: number) => [n.name, i])), beams: [], tris: [], wheels: [], flexbodies: [], parts: [], partsByName: new Map(), tables: new Map(), triggers: [], props: [], ...extra } as any;
}

it('duplicate beams: copies are warnings, deliberate pairs are notes', () => {
  const run = (beams: any[]) => runChecks(vehicle({ beams }), opts, new Set(['duplicateBeams']))[0];
  // a copy, even with other stiffness values from its block
  expect(run([beam(0, 1, { beamSpring: 3201000, beamDamp: 80 }), beam(1, 0, { beamSpring: 3501000, beamDamp: 70 }, 9)]).sev).toBe('warning');
  const pair = run([beam(0, 1, { beamSpring: 50000, beamDamp: 0 }), beam(0, 1, { beamSpring: 0, beamDamp: 2000 }, 9)]);
  expect(pair.sev).toBe('info');
  expect(pair.fix).toBeUndefined();
  expect(pair.msg).toMatch(/spring \+ damper/);
  expect(run([beam(0, 1), beam(0, 1, { beamType: '|BOUNDED' }, 9)]).msg).toMatch(/different beam types/);
  expect(run([beam(0, 1), beam(0, 1, {}, 9)]).beams).toEqual([0, 1]);
});

it('coincident nodes: couplers are left alone', () => {
  const nodes = [node('f1r', 0), node('fx2r', 0, { tag: 'fx2r' }), node('b1', 1, { couplerTag: 'x' }), node('h6', 1), node('c1', 2), node('c2', 2)];
  const f = runChecks(vehicle({ nodes }), opts, new Set(['closeNodes']));
  expect(f.map((x) => x.msg)).toEqual(['c1 & c2: 0.00 mm']);
});

it('coincident nodes: latch pairs of advancedCouplerControl blocks are left alone', () => {
  const ast = parseSjson('{"couplerNodes": [["cid1", "cid2", "autoCouplingStrength"], ["c2", "c1", 40000]]}').root;
  const nodes = [node('c1', 2), node('c2', 2), node('d1', 3), node('d2', 3)];
  const f = runChecks(vehicle({ nodes, parts: [{ def: { name: 'door', file: 'f', sections: new Map([['door_coupler', ast]]) } }] }), opts, new Set(['closeNodes']));
  expect(f.map((x) => x.msg)).toEqual(['d1 & d2: 0.00 mm']);
});

it('flexbody groups: groups generated by wheel rows count', () => {
  const v = vehicle({
    wheels: [{ row: row({ hubGroup: 'wheelhub_FR', group: 'wheel_FR' }) }],
    flexbodies: [{ mesh: 'brake_disc', groups: ['wheelhub_FR'] }, { mesh: 'tire', groups: ['tire_FR', 'wheel_FR'] }, { mesh: 'swaybar', groups: ['swaybar_F'] }].map((f) => ({ ...f, row: row() })),
  });
  expect(runChecks(v, opts, new Set(['flexGroups'])).map((x) => x.msg)).toEqual(['swaybar: swaybar_F']);
});

it('flexbody groups: says when the group only exists in commented-out nodes', () => {
  const text = [
    '{"p": {',
    '  "flexbodies": [["mesh", "[group]:"], ["swaybar", ["swaybar_F"]]],',
    '  /* "nodes": [',
    '    ["id", "posX", "posY", "posZ"],',
    '    {"group":"swaybar_F"},',
    '    ["arb1", 0, 0, 0],',
    '  ], */',
    '  // {"group":["body", "other_F"]},',
    '}}',
  ].join('\n');
  const v = vehicle({ flexbodies: [{ mesh: 'swaybar', groups: ['swaybar_F'], row: row() }, { mesh: 'x', groups: ['other_F'], row: row() }, { mesh: 'y', groups: ['nowhere'], row: row() }] });
  const f = runChecks(v, { ...opts, texts: [{ file: 'vehicles/p/p.jbeam', text }] }, new Set(['flexGroups']));
  expect(f.map((x) => x.msg)).toEqual([
    'swaybar: swaybar_F (its nodes are commented out: p.jbeam, line 5)',
    'x: other_F (its nodes are commented out: p.jbeam, line 8)',
    'y: nowhere',
  ]);
  expect(text.slice(f[0].src!.s, f[0].src!.e)).toBe('"swaybar_F"');
});
