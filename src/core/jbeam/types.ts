import type { AArr, ANode, AObj, AStr, ParseIssue, Severity } from '../sjson';
import type { Scope } from './expr';

/** Where an assembled element comes from in the source text. */
export interface SrcRef {
  file: string;
  part: string;
  section: string;
  /** The table row (array) or dict entry value this element was built from. */
  node: ANode;
  /** The table (section value) containing the row. */
  table: ANode;
}

export interface SlotDef {
  name: string;
  /** slots v1 only */
  type?: string;
  allowTypes: string[];
  denyTypes: string[];
  default?: string;
  description: string;
  coreSlot?: boolean;
  maxRecursion?: number;
  /** Slot-scoped variables (raw, unresolved). */
  variables?: Record<string, any>;
  /** Remaining slot options, inherited by everything below this slot (nodeOffset etc). Raw, unresolved. */
  options: Record<string, any>;
  row?: ANode;
  table?: ANode;
}

export interface PartDef {
  name: string;
  file: string;
  node: AObj;
  key: AStr;
  slotTypes: string[];
  slots: SlotDef[];
  info: { name?: string; authors?: string; value?: number };
  /** Section name -> AST value, in source order */
  sections: Map<string, ANode>;
  sectionKeys: Map<string, AStr>;
}

export interface JFile {
  path: string;
  text: string;
  root: ANode | null;
  issues: ParseIssue[];
  parts: PartDef[];
}

export interface Issue {
  sev: Severity;
  msg: string;
  code: string;
  file?: string;
  s?: number;
  e?: number;
  part?: string;
}

export interface SlotNode {
  id: string;
  path: string;
  def: SlotDef;
  owner: ActivePart;
  /** Name of the chosen part, '' when empty. */
  chosen: string;
  /** What the config asked for (may differ from chosen when missing/unfit). */
  wanted?: string;
  decision: 'user' | 'default' | 'user-empty' | 'default-empty' | 'missing' | 'empty';
  part?: ActivePart;
}

export interface ActivePart {
  def: PartDef;
  /** e.g. /pickup/pickup_body/pickup_frame */
  path: string;
  level: number;
  parent?: ActivePart;
  slot?: SlotNode;
  /** Accumulated, variable-resolved slot options. */
  slotOptions: Record<string, any>;
  scope: Scope;
  slots: SlotNode[];
  /** pre-order index */
  order: number;
}

export interface Row {
  /** Merged values: inherited modifiers + header-mapped cells + inline options. */
  v: Record<string, any>;
  src: SrcRef;
  part: ActivePart;
}

export type BeamType = 'NORMAL' | 'HYDRO' | 'ANISOTROPIC' | 'BOUNDED' | 'PRESSURED' | 'SUPPORT' | 'LBEAM' | 'BROKEN';

export interface VNode {
  name: string;
  idx: number;
  x: number;
  y: number;
  z: number;
  /** Raw (pre-transform) position as written in the file; null when a cell is not a plain number. */
  raw: [number, number, number] | null;
  row: Row;
  groups: string[];
  /** Generated by a wheel / rope etc, not present in the text. */
  virtual?: boolean;
}

export interface VBeam {
  a: number;
  b: number;
  type: BeamType;
  section: string;
  row: Row;
}

export interface VTri {
  a: number;
  b: number;
  c: number;
  section: string;
  row: Row;
}

export interface VWheel {
  name: string;
  section: string;
  n1: number;
  n2: number;
  nodeArm: number;
  nodeS: number;
  radius: number;
  hubRadius: number;
  tireWidth: number;
  hubWidth: number;
  wheelOffset: number;
  wheelDir: number;
  hasTire: boolean;
  numRays: number;
  row: Row;
}

export interface VFlexbody {
  mesh: string;
  groups: string[];
  pos: [number, number, number] | null;
  rot: [number, number, number] | null;
  scale: [number, number, number] | null;
  row: Row;
}

export interface VProp {
  func: string;
  mesh: string;
  idRef: number;
  idX: number;
  idY: number;
  row: Row;
}

export interface VarDef {
  name: string;
  type: string;
  unit?: string;
  category?: string;
  default: number;
  min: number;
  max: number;
  title?: string;
  description?: string;
  val: number;
  part: string;
  file: string;
  row?: ANode;
}

export interface VehicleConfig {
  mainPartName?: string;
  parts?: Record<string, string>;
  vars?: Record<string, number>;
  model?: string;
}

export interface Vehicle {
  mainPart: string;
  root: ActivePart;
  /** Active parts in merge (pre-order) order. */
  parts: ActivePart[];
  partsByName: Map<string, ActivePart>;
  options: Record<string, any>;
  /** Table sections: processed rows. */
  tables: Map<string, Row[]>;
  headers: Map<string, string[]>;
  /** Dictionary sections merged across parts. */
  dicts: Map<string, Record<string, any>>;
  nodes: VNode[];
  nodeIndex: Map<string, number>;
  beams: VBeam[];
  tris: VTri[];
  wheels: VWheel[];
  flexbodies: VFlexbody[];
  props: VProp[];
  variables: VarDef[];
  vars: Scope;
  issues: Issue[];
  refNodes: Record<string, string>;
}

export type { AArr, ANode, AObj, AStr, ParseIssue };
